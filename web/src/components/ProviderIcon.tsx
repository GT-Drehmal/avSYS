/**
 * A sign-in provider's mark, beside its name: decorative, since the name
 * says which it is. The install's own OpenID Connect provider, and any
 * other, have a key.
 */
export function ProviderIcon({ id, className }: { id: string; className?: string }) {
  const mark = marks[id];
  const cls = cx("size-[16px] shrink-0", className);
  if (!mark) return <KeyRound aria-hidden data-provider-icon={id} className={cx(cls, "text-muted")} />;
  return (
    <svg aria-hidden focusable="false" viewBox="0 0 24 24" data-provider-icon={id} className={cls}>
      {mark}
    </svg>
  );
}
